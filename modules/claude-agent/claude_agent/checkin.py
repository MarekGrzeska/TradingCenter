"""Check-ins (`claude-agent-runtime`): at the configured times a skill is typed into the session so the agent writes
first — unless the operator wrote in the last hour. One due while the session was down is delivered when it is back,
within the hour, once. Decisions are pure functions; the CLI at the bottom reads state, asks tmux and types.

    python -m claude_agent.checkin crontab          the scheduler's lines for AGENT_CHECKINS
    python -m claude_agent.checkin slot HH:MM       a check-in is due now
    python -m claude_agent.checkin pending          deliver one that was due while the session was down (every 5 min)
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import time
from dataclasses import dataclass
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any
from zoneinfo import ZoneInfo

DEFAULT_CHECKINS = "08:30 przeglad-rana,21:30 podsumowanie-dnia"
ACTIVE_WINDOW = timedelta(hours=1)
PENDING_MAX = timedelta(hours=1)
SESSION_READY = timedelta(seconds=30)
SESSION = "agent"
# The operator's clock, which the slots are written in; the image sets the same zone as TZ.
ZONE = ZoneInfo("Europe/Warsaw")
_SLOT = re.compile(r"^([01]\d|2[0-3]):[0-5]\d$")
_SKILL = re.compile(r"^[a-z0-9-]+$")
_CHANNEL = re.compile(r"<channel\s+[^>]*source=\"[^\"]*telegram[^\"]*\"")


@dataclass(frozen=True)
class Checkin:
    slot: str
    skill: str


def parse_checkins(value: str | None) -> list[Checkin]:
    """Empty means the default pair; `none` turns check-ins off. Anything malformed refuses rather than guesses."""
    text = (value or "").strip()
    if text == "":
        text = DEFAULT_CHECKINS
    if text.lower() == "none":
        return []
    checkins: dict[str, Checkin] = {}
    for part in filter(None, (p.strip() for p in text.split(","))):
        slot, _, skill = part.partition(" ")
        skill = skill.strip()
        if not _SLOT.match(slot) or not _SKILL.match(skill):
            raise ValueError(f'AGENT_CHECKINS: "{part}" is not "HH:MM skill"')
        checkins[slot] = Checkin(slot, skill)
    return sorted(checkins.values(), key=lambda c: c.slot)


def crontab(checkins: list[Checkin], bin_dir: str, python: str) -> str:
    run = f"{python} -m claude_agent.checkin"
    lines = ["# generated by entrypoint.sh from AGENT_CHECKINS - do not edit"]
    for checkin in checkins:
        hour, minute = checkin.slot.split(":")
        lines.append(f"{int(minute)} {int(hour)} * * * {run} slot {checkin.slot}")
    lines += [
        f"*/5 * * * * {run} pending",
        f"* * * * * {bin_dir}/channel-watchdog.sh",
        f"0 4 * * * {bin_dir}/restart.sh",
    ]
    return "\n".join(lines) + "\n"


def decide_slot(
    *, slot: str, now: datetime, handled: set[str], last_operator: datetime | None, session_up: bool
) -> str:
    if f"{now:%Y-%m-%d} {slot}" in handled:
        return "skip-handled"
    if last_operator is not None and now - last_operator < ACTIVE_WINDOW:
        return "skip-active"
    return "send" if session_up else "pending"


def decide_pending(
    *, pending: dict[str, Any], now: datetime, slots: list[str], handled: set[str], session_up: bool
) -> str:
    if pending["day"] != f"{now:%Y-%m-%d}" or f"{pending['day']} {pending['slot']}" in handled:
        return "drop"
    if now - datetime.fromtimestamp(pending["at"], tz=ZONE) > PENDING_MAX:
        return "drop"
    later = [s for s in slots if s > pending["slot"]]
    if later and f"{now:%H:%M}" >= later[0]:
        return "drop"
    return "send" if session_up else "wait"


def _operator_wrote(entry: dict[str, Any]) -> bool:
    """A Telegram message, or something typed by a person (Remote Control); never a typed-in check-in, a tool result
    or a skill body."""
    if entry.get("type") != "user" or entry.get("isSidechain") or entry.get("isCompactSummary"):
        return False
    message = entry.get("message") or {}
    content = message.get("content")
    if isinstance(content, list):
        if any(isinstance(c, dict) and c.get("type") == "tool_result" for c in content):
            return False
        content = "\n".join(c.get("text", "") for c in content if isinstance(c, dict))
    text = (content or "").strip() if isinstance(content, str) else ""
    if _CHANNEL.search(text):
        return True
    if entry.get("isMeta") or (entry.get("origin") or {}).get("kind") not in (None, "human"):
        return False
    return text != "" and not text.startswith(("<", "/", "Base directory for this skill:"))


def last_operator_activity(project_dir: Path) -> datetime | None:
    if not project_dir.is_dir():
        return None
    transcripts = sorted(
        project_dir.glob("*.jsonl"), key=lambda p: p.stat().st_mtime, reverse=True
    )[:2]
    for transcript in transcripts:
        for line in reversed(transcript.read_text(encoding="utf-8").splitlines()):
            try:
                entry = json.loads(line)
            except ValueError:
                continue
            if isinstance(entry, dict) and _operator_wrote(entry):
                try:
                    stamp = datetime.fromisoformat(entry["timestamp"])
                except (KeyError, ValueError, AttributeError):
                    continue
                return stamp.astimezone(ZONE)
    return None


def read_handled(path: Path) -> set[str]:
    if not path.exists():
        return set()
    return {line.strip() for line in path.read_text(encoding="utf-8").splitlines() if line.strip()}


def mark_handled(path: Path, key: str, now: datetime) -> None:
    cutoff = f"{now - timedelta(days=7):%Y-%m-%d}"
    kept = sorted({k for k in read_handled(path) if k[:10] >= cutoff} | {key})
    path.write_text("\n".join(kept) + "\n", encoding="utf-8")


def project_dir(config_dir: Path, workdir: str) -> Path:
    """Claude Code keeps a project's transcripts in a directory named after the working directory."""
    return config_dir / "projects" / re.sub(r"[^A-Za-z0-9]", "-", workdir)


def _session_ready(now: datetime) -> bool:
    result = subprocess.run(
        ["tmux", "display-message", "-p", "-t", SESSION, "#{session_created}"],
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0 or not result.stdout.strip().isdigit():
        return False
    return now - datetime.fromtimestamp(int(result.stdout.strip()), tz=ZONE) >= SESSION_READY


def _type(text: str) -> None:
    subprocess.run(["tmux", "send-keys", "-t", SESSION, "-l", text], check=True)
    subprocess.run(["tmux", "send-keys", "-t", SESSION, "Enter"], check=True)


def main(argv: list[str]) -> int:
    env = os.environ
    workdir = env.get("AGENT_WORKDIR", "/home/agent/work")
    config_dir = Path(env.get("CLAUDE_CONFIG_DIR", "/home/agent/.claude"))
    state = Path(env.get("AGENT_STATE_DIR", f"{config_dir}/agent-state"))
    state.mkdir(parents=True, exist_ok=True)
    handled_file, pending_file = state / "check-in", state / "check-in-pending.json"
    checkins = parse_checkins(env.get("AGENT_CHECKINS"))
    skill_of = {c.slot: c.skill for c in checkins}
    now = datetime.now(tz=ZONE)

    def log(message: str) -> None:
        print(f"[checkin {now:%Y-%m-%d %H:%M}] {message}")

    match argv:
        case ["crontab"]:
            sys.stdout.write(
                crontab(checkins, env.get("AGENT_BIN", "/opt/agent/bin"), sys.executable)
            )
        case ["slot", slot] if slot in skill_of:
            decision = decide_slot(
                slot=slot,
                now=now,
                handled=read_handled(handled_file),
                last_operator=last_operator_activity(project_dir(config_dir, workdir)),
                session_up=_session_ready(now),
            )
            key = f"{now:%Y-%m-%d} {slot}"
            if decision == "send":
                _type(f"/{skill_of[slot]}")
                mark_handled(handled_file, key, now)
            elif decision == "skip-active":
                mark_handled(handled_file, key, now)
            elif decision == "pending":
                pending = {"day": f"{now:%Y-%m-%d}", "slot": slot, "at": time.time()}
                pending_file.write_text(json.dumps(pending), encoding="utf-8")
            log(f"slot {slot}: {decision}")
        case ["pending"]:
            if not pending_file.exists():
                return 0
            pending = json.loads(pending_file.read_text(encoding="utf-8"))
            decision = decide_pending(
                pending=pending,
                now=now,
                slots=sorted(skill_of),
                handled=read_handled(handled_file),
                session_up=_session_ready(now),
            )
            if decision == "send" and pending["slot"] in skill_of:
                _type(f"/{skill_of[pending['slot']]}")
                mark_handled(handled_file, f"{pending['day']} {pending['slot']}", now)
            if decision != "wait":
                pending_file.unlink(missing_ok=True)
            log(f"pending {pending['slot']}: {decision}")
        case _:
            print(__doc__, file=sys.stderr)
            return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
